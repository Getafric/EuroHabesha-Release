/// Display translations only: stored service identifiers are preserved.
String activityText(BuildContext context, String value) {
  final french = _legacyFrench[value] ?? value;
  final english =
      _activityEnglish[value] ??
      (_legacyFrench.containsKey(value) ? value : french);
  return memberText(context, french, english);
}

String activityCountryLabel(BuildContext context, String value) {
  final country = BusinessCountries.find(value);
  if (country == null) {
    return value;
  }
  return memberText(
    context,
    country.name,
    _countryEnglish[country.code] ?? country.name,
  );
}

